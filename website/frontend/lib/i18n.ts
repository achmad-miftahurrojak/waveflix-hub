export function useTranslation() {
  const { user } = useAuth();

  const lang = user?.language && translations[user.language] ? user.language : "id";

  const t = useCallback(
    (key: string): string => {
      return translations[lang]?.[key] || key;
    },
    [lang]
  );

  return { t, lang };
}
